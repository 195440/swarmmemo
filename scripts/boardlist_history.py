#!/usr/bin/env python3
"""Derive the agent board map's growth from the git history of its list (C457).

Reads every commit of boards.json in the internal/web/boardlist submodule
(github.com/Hugo0/awesome-agent-boards) and writes
internal/web/boardlist_history.json: for each UTC day with a change, the last
commit of that day and how many entries each group held after it. The server
cannot read git history at run time, so /boards/state embeds this file; a test
holds its last point to the embedded list, so bumping the submodule without
re-running this fails the build.

The submodule must be a full clone (not shallow). Standard library only.

Usage: python3 scripts/boardlist_history.py
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIST = ROOT / "internal/web/boardlist"
OUT = ROOT / "internal/web/boardlist_history.json"
GROUPS = ("verified", "reported", "completeness")


def git(*args):
    return subprocess.run(["git", "-C", str(LIST), *args], check=True, capture_output=True, text=True).stdout


def main():
    if git("rev-parse", "--is-shallow-repository").strip() == "true":
        raise SystemExit("internal/web/boardlist is shallow: git -C internal/web/boardlist fetch --unshallow")
    points = {}
    for line in git("log", "--reverse", "--format=%H %cs", "--", "boards.json").splitlines():
        commit, day = line.split()
        boards = json.loads(git("show", commit + ":boards.json"))["boards"]
        point = {"date": day, "commit": commit[:12]}
        for group in GROUPS:
            point[group] = sum(1 for b in boards if b.get("group") == group)
        points[day] = point  # the day's last commit wins
    out = {"source": "https://github.com/Hugo0/awesome-agent-boards", "file": "boards.json",
           "note": "Entries per group after the last commit of each day that changed the list. Generated by scripts/boardlist_history.py.",
           "points": list(points.values())}
    OUT.write_text(json.dumps(out, indent=1) + "\n")


if __name__ == "__main__":
    main()
